// Paste into the landing page console and run await checkNoodleAppExamples().
async function checkNoodleAppExamples(doc = document) {
  const demo = doc.querySelector('[data-noodle-demo]')
  const view = doc.defaultView
  const chapter = (id) => demo.querySelector(`[data-tour-option="${id}"]`)
  const surface = () => demo.querySelector('[data-app-surface]:not([hidden])')
  const choose = (id) => chapter(id).click()
  const search = (value) => {
    const input = surface().querySelector('[data-picker-search]')
    input.value = value
    input.dispatchEvent(new view.Event('input', { bubbles: true }))
    return input
  }
  const key = (target, name) => target.dispatchEvent(new view.KeyboardEvent('keydown', { key: name, bubbles: true, cancelable: true }))
  const close = () => demo.querySelector('[data-app-return]').click()
  const requests = () => surface().querySelectorAll('[data-runner-request][aria-pressed="true"]')
  const fetches = () => view.performance.getEntriesByType('resource').filter((entry) => ['fetch', 'xmlhttprequest'].includes(entry.initiatorType)).length
  const before = fetches()
  let passed = 0
  const assert = (condition, message) => { if (!condition) throw new Error(message); passed++ }
  const waitFor = async (condition) => {
    const deadline = view.performance.now() + 4000
    while (!condition()) {
      if (view.performance.now() > deadline) throw new Error('Timed out waiting for sample runner')
      await new Promise((resolve) => view.requestAnimationFrame(resolve))
    }
  }
  const play = demo.querySelector('[data-tour-play]')
  if (play.getAttribute('aria-label') === 'Pause tour') play.click()
  choose('commands')
  assert(surface().querySelectorAll('[data-picker-option]').length === 12, 'Palette includes twelve original Noodle commands')
  assert(surface().querySelectorAll('[data-picker-section]').length === 4, 'Commands share one heading per native category')
  search('environment')
  assert(surface().querySelectorAll('[data-picker-option]:not([hidden])').length === 3, 'Environment search includes selection, cycling, and editing')
  let input = search('open environment')
  assert(surface().querySelectorAll('[data-picker-option]:not([hidden])').length === 1, 'Command search filters sections and commands')
  key(input, 'Enter')
  assert(surface().dataset.appSurface === 'environments', 'Enter executes the highlighted command')
  surface().querySelector('[data-demo-env="staging"]').click()
  let panel = surface().querySelector('[data-env-panel]:not([hidden])')
  assert(panel.dataset.envPanel === 'staging' && panel.querySelector('input').value.includes('staging'), 'Environment selection changes variable values')
  const token = panel.querySelector('[data-env-secret]')
  const reveal = panel.querySelector('[data-env-reveal]')
  reveal.click()
  assert(token.value === token.dataset.envSecret && reveal.getAttribute('aria-pressed') === 'true' && reveal.textContent === '[secret]', 'Sample secret reveals without changing its native badge')
  reveal.click()
  assert(token.value === '••••••••' && reveal.getAttribute('aria-pressed') === 'false', 'Secrets use the native fixed eight-character mask')
  reveal.click()
  surface().querySelector('[data-demo-env="development"]').click()
  assert(token.value === '••••••••', 'Switching environments remasks secrets')
  const value = surface().querySelector('[data-env-panel]:not([hidden]) input')
  const originalValue = value.value
  value.value = 'https://edited.example.com'
  value.dispatchEvent(new view.Event('input', { bubbles: true }))
  surface().querySelector('[data-demo-env="staging"]').click()
  surface().querySelector('[data-demo-env="development"]').click()
  assert(value.value === 'https://edited.example.com', 'Sample edits survive environment selection')
  value.value = originalValue
  const toggle = value.closest('tr').querySelector('[data-env-toggle]')
  toggle.click()
  assert(toggle.getAttribute('aria-pressed') === 'false' && value.closest('tr').classList.contains('env-disabled'), 'Variable toggles update the row state')
  toggle.click()
  const nameInput = surface().querySelector('input[data-env-name]')
  const colorInput = surface().querySelector('input[data-env-color]')
  nameInput.value = 'local development'
  nameInput.dispatchEvent(new view.Event('input', { bubbles: true }))
  colorInput.value = 'info'
  colorInput.dispatchEvent(new view.Event('change', { bubbles: true }))
  surface().querySelector('[data-demo-env="staging"]').click()
  surface().querySelector('[data-demo-env="development"]').click()
  assert(nameInput.value === 'local development' && colorInput.value === 'info', 'Environment name and color edits survive selection')
  assert(surface().querySelectorAll('[data-env-name]').length === 1 && surface().querySelectorAll('[data-env-color]').length === 1 && surface().querySelector('[data-env-panel]:not([hidden])').getBoundingClientRect().width > 0, 'Draft state does not collide with control styles or selectors')
  nameInput.value = 'development'
  nameInput.dispatchEvent(new view.Event('input', { bubbles: true }))
  colorInput.value = 'success'
  colorInput.dispatchEvent(new view.Event('change', { bubbles: true }))
  const addRow = surface().querySelector('[data-env-panel="development"] [data-env-add]')
  assert(addRow.querySelector('[data-env-add-key]').placeholder === 'Key...' && addRow.querySelector('[data-env-add-value]').placeholder === 'Value...', 'Environment shows its native blank variable row')
  addRow.querySelector('[data-env-add-key]').value = 'local_sample'
  addRow.querySelector('[data-env-add-value]').value = 'sample value'
  key(addRow.querySelector('[data-env-add-key]'), 'Enter')
  const added = addRow.previousElementSibling
  assert(added.querySelector('th').textContent === 'local_sample' && added.querySelector('[data-env-value]').value === 'sample value', 'Adding a sample variable commits local values')
  added.querySelector('[data-env-toggle]').click()
  assert(added.classList.contains('env-disabled'), 'New variable uses the existing enable control')
  added.remove()
  close()
  await waitFor(() => view.getComputedStyle(demo.querySelector('[data-example]:not([hidden])')).visibility === 'visible')
  assert(view.getComputedStyle(demo.querySelector('[data-example]:not([hidden])')).visibility === 'visible', 'Closing a full workspace restores request visibility')
  choose('finder')
  assert(!surface().querySelector('.finder-tags') && ![...surface().querySelectorAll('[data-picker-option]')].some((option) => option.textContent.includes('#')), 'Finder displays no tags')
  input = search('check get')
  assert(surface().querySelectorAll('[data-picker-option]:not([hidden])').length === 1, 'Finder searches request names and methods')
  key(input, 'Enter')
  assert(!surface() && demo.querySelector('[data-example]:not([hidden])').dataset.example === 'assert-post', 'Finder selection opens the matching request')
  choose('finder')
  search('no-such-request')
  assert(!surface().querySelector('[data-picker-empty]').hidden && !surface().querySelector('[data-picker-search]').hasAttribute('aria-activedescendant'), 'Empty search has no stale selection')
  key(surface().querySelector('input'), 'Escape')
  assert(surface(), 'Escape hint is only a reference')
  close()
  choose('themes')
  assert(surface().querySelectorAll('[data-demo-theme]').length === 35, 'All original Noodle themes are available in the demo')
  const originalPalette = view.getComputedStyle(demo).getPropertyValue('--demo-primary')
  const originalSiteTheme = doc.documentElement.dataset.siteTheme
  input = search('noodle')
  assert(view.getComputedStyle(demo).getPropertyValue('--demo-primary').trim() === '#59c9be', 'Highlighted theme previews across the demo')
  close()
  assert(view.getComputedStyle(demo).getPropertyValue('--demo-primary') === originalPalette && doc.documentElement.dataset.siteTheme === originalSiteTheme, 'Closing cancels preview and preserves the site palette')
  choose('themes')
  input = search('carbonfox')
  key(input, 'Enter')
  assert(!surface() && view.getComputedStyle(demo).getPropertyValue('--demo-primary').trim() === '#33b1ff', 'Theme selection keeps the demo palette')
  choose('themes')
  input = search('noodle')
  close()
  assert(view.getComputedStyle(demo).getPropertyValue('--demo-primary').trim() === '#33b1ff', 'Cancel restores the last selected demo theme')
  choose('runner')
  const runner = surface()
  await waitFor(() => view.getComputedStyle(demo.querySelector('.collection')).visibility === 'hidden')
  assert(view.getComputedStyle(demo.querySelector('.collection')).visibility === 'hidden', 'Full runner workspace hides the underlying request labels')
  assert(requests().length === 6, 'Runner starts with six existing request fixtures')
  assert(runner.querySelector('[data-runner-tab="results"]').hidden, 'Results tab appears only after a run starts')
  const filter = runner.querySelector('[data-runner-filter="include"][data-tag="smoke"]')
  filter.click()
  assert(requests().length === 1 && runner.querySelector('[data-runner-run]').textContent.includes('Run 1 request'), 'Include filter updates selection and execution count')
  runner.querySelector('[data-runner-filter="exclude"][data-tag="smoke"]').click()
  assert(requests().length === 0 && runner.querySelector('[data-runner-run]').disabled, 'Conflicting filters disable an empty run')
  runner.querySelector('[data-runner-filter="exclude"][data-tag="smoke"]').click()
  const delay = runner.querySelector('[data-runner-delay]')
  delay.value = '-1'
  delay.dispatchEvent(new view.Event('input', { bubbles: true }))
  assert(!runner.querySelector('[data-runner-error]').hidden && runner.querySelector('[data-runner-run]').disabled, 'Invalid delay prevents a run and explains recovery')
  delay.value = '0'
  delay.dispatchEvent(new view.Event('input', { bubbles: true }))
  const data = runner.querySelector('[data-runner-data]')
  data.value = './data/users.csv'
  data.dispatchEvent(new view.Event('input', { bubbles: true }))
  assert(runner.querySelector('[data-runner-run]').textContent.includes('Run 2 requests'), 'Data fixture adds two iterations')
  runner.querySelector('[data-runner-run]').click()
  assert(runner.getAttribute('aria-busy') === 'true' && delay.disabled, 'Running locks configuration and exposes busy state')
  await waitFor(() => !runner.hasAttribute('aria-busy'))
  assert(runner.querySelectorAll('.runner-result').length === 2 && runner.querySelector('[data-runner-summary]').textContent.includes('2/2 passed'), 'Runner completes both sample iterations')
  runner.querySelector('.runner-result summary').click()
  assert(runner.querySelector('.runner-result').open && runner.querySelector('.runner-result pre').textContent.includes('200 OK'), 'Run result opens its sample response detail')
  runner.querySelector('[data-runner-run]').click()
  close()
  await new Promise((resolve) => view.setTimeout(resolve, 250))
  assert(!runner.hasAttribute('aria-busy') && runner.querySelectorAll('.runner-result').length === 0, 'Leaving the runner cancels its pending sample work')
  const command = (label) => {
    choose('commands')
    const input = search(label)
    assert(surface().querySelectorAll('[data-picker-option]:not([hidden])').length === 1, `${label} is searchable`)
    key(input, 'Enter')
  }
  command('cycle environment')
  assert(demo.querySelector('[data-active-environment]').textContent === 'staging', 'Cycle Environment switches the active environment')
  command('select environment')
  assert(surface().dataset.appSurface === 'env-picker', 'Select Environment opens its native picker')
  input = search('production')
  key(input, 'Enter')
  assert(!surface() && demo.querySelector('[data-active-environment]').textContent === 'production', 'Environment picker selection updates the active environment')
  command('toggle layout')
  assert(demo.querySelector('.terminal-layout').classList.contains('side-by-side'), 'Toggle Layout places request and response side by side')
  command('toggle layout')
  assert(!demo.querySelector('.terminal-layout').classList.contains('side-by-side'), 'Toggle Layout restores stacked panes')
  command('toggle sidebar')
  assert(demo.querySelector('.collection').hidden, 'Toggle Sidebar hides the request tree')
  command('toggle sidebar')
  assert(!demo.querySelector('.collection').hidden, 'Toggle Sidebar restores the request tree')
  command('expand/collapse')
  assert(demo.querySelector('[data-example]:not([hidden])').classList.contains('is-expanded'), 'Expand command expands the request pane')
  command('expand/collapse')
  assert(!demo.querySelector('[data-example]:not([hidden])').classList.contains('is-expanded'), 'Expand command collapses the expanded pane')
  command('send request')
  assert(demo.querySelector('[data-example]:not([hidden]) [data-send]').getAttribute('aria-disabled') === 'true', 'Send Request starts the local sample response')
  await waitFor(() => demo.querySelector('[data-example]:not([hidden]) [data-send]').getAttribute('aria-disabled') !== 'true')
  command('keyboard shortcuts')
  assert(surface().dataset.appSurface === 'help' && surface().textContent.includes('^alt+r'), 'Keyboard Shortcuts opens the supported native keybindings')
  close()
  command('script execution order')
  assert(surface().dataset.appSurface === 'order' && surface().querySelectorAll('li').length === 1, 'Execution Order shows the actual request script in the sample collection')
  close()
  choose('environments')
  surface().querySelector('[data-demo-env="development"]').click()
  close()
  const panelBefore = demo.querySelector('[data-example]:not([hidden]) .request [role="tabpanel"]:not([hidden])')
  panelBefore.focus()
  for (const options of [{key:'p',ctrlKey:true}, {key:'f',ctrlKey:true}, {key:'t',ctrlKey:true}, {key:'Enter',ctrlKey:true}, {key:'b',code:'KeyB',ctrlKey:true,altKey:true}, {key:'F1'}, {key:'F2'}, {key:'F3'}, {key:'F5'}]) {
    const event = new view.KeyboardEvent('keydown', {...options,bubbles:true,cancelable:true})
    panelBefore.dispatchEvent(event)
    assert(!event.defaultPrevented && !surface() && !demo.querySelector('[data-example]:not([hidden])').classList.contains('is-expanded') && demo.querySelector('[data-example]:not([hidden]) [data-send]').getAttribute('aria-disabled') !== 'true', `${options.key} shortcut is only a reference`)
  }
  choose('runner')
  key(surface().querySelector('[data-runner-run]'), 'r')
  assert(!surface().hasAttribute('aria-busy'), 'Runner r shortcut is only a reference')
  close()
  assert(fetches() === before, 'All examples operate without API fetches')
  return { passed }
}
